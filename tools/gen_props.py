def pine(leaf, snow=None):
    tiers = [(-2, 12, 9), (-11, 10, 9), (-19, 7.5, 8), (-26, 5, 7)]
    shape = [("p", [(-2, 0), (2, 0), (2, -6), (-2, -6)], TRUNK)]
    for y, w, h in tiers:
        shape.append(("p", [(-w, y), (w, y), (0, y - h - 4)], leaf))
        if snow:
            shape.append(("p", [(-w * 0.55, y - h * 0.45), (w * 0.4, y - h * 0.5), (0, y - h - 3)], snow))
    return shape


