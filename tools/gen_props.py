def make_props(out_dir):
    out = out_dir / "props"
    out.mkdir(parents=True, exist_ok=True)
    for name, sp in PROPS.items():
        spec = dict(sp, eyes=[])
        render_fit(spec, sp["size"], 1.0, back=False).save(out / f"{name}.png")
    return list(PROPS)


